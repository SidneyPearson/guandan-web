'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { io } = require('socket.io-client');
const { createApp } = require('../../server/index.cjs');
const GD = require('../../server/runtime.cjs');
const { PROTOCOL } = require('../../js/online-view.js');
const { launch, waitFor } = require('./cdp.cjs');
const evidence = path.join(__dirname, '../online-evidence');
fs.mkdirSync(evidence, { recursive: true });
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'gd-online-browser-'));
