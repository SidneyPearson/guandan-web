const peers = [], browsers = [];
async function screenshot(cdp, name) {
  await new Promise(resolve => setTimeout(resolve, 250));
  const result = await cdp.send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync(path.join(evidence, name + '.png'), Buffer.from(result.data, 'base64'));
}
async function peer(base, code, mode) {
  const s = io(base, { transports: ['websocket'], forceNew: true }); peers.push(s);
  await new Promise((resolve, reject) => { s.once('connect', resolve); s.once('connect_error', reject); });
  const send = data => s.timeout(5000).emitWithAck('request', { protocol: PROTOCOL, version: GD.VERSION, requestId: crypto.randomUUID(), ...data });
  assert.equal((await send({ kind: 'room:join', code, mode, nickname: '朋友' + peers.length })).ok, true);
  await send({ kind: 'room:ready' }); return { s, send };
}
