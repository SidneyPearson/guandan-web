/* Generated classic worker payload for file://, where importScripts is restricted.
 * Single-source implementation: never edit the generated bundle by hand.
 */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const dir=path.resolve(__dirname,'../js');
function build(){
  const files=['util','cards','rules','flow','ai','ai-memory','ai-search','game'];
  const worker=fs.readFileSync(path.join(dir,'ai-worker.js'),'utf8');
  const source='self.window=self;\n'+files.map(n=>fs.readFileSync(path.join(dir,n+'.js'),'utf8')).join('\n')+'\n'+worker.slice(worker.indexOf('self.onmessage='));
  const hash=crypto.createHash('sha256').update(source).digest('hex');
  return '/* GENERATED by tools/build-ai-worker.cjs; source sha256: '+hash+' */\n'+
    '(function(){const GD=window.GD=window.GD||{};GD.AI_WORKER_SOURCE='+JSON.stringify(source)+';})();\n';
}
if(require.main===module){fs.writeFileSync(path.join(dir,'ai-worker-source.js'),build());console.log('Built file:// AI worker from shared sources');}
module.exports=build;
